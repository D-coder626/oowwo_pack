// oowwo: mortar consolidation (Derek, 2026-09-27; Hexerei + Hexalia removed 2026-10-17).
//
// ONE general mortar: Toxony's (toxony:mortar_pestle) - up to 4 ingredients, can consume a
// container (bowl / empty pot), and has the Redstone Mortar for automation. Its crafting recipe uses
// Wayfarer's mortar materials (Derek: "same material tier as wayfarer's").
// Wayfarer's mortar block is craftable again (2026-10-17, Derek) with its original Wayfarer recipe.
// Wayfarer's pestle is an ingredient of Toxony's mortar.
// Hexerei and Hexalia (and their mortars) were removed from the pack on 2026-10-17; their mortar
// recipes (13 Hexalia, 4 Hexerei) went with the jars.
//
// Every former wayfarer_core:grinding recipe was rewritten as toxony:mortar_pestle in its own
// script (wayfarer_port.js, oowwo_wheat.js, oowwo_misc.js, oowwo_small_ports.js). Toxony has no
// bonus roll, so outputs are Wayfarer's expected value rounded.
//
// THIS FILE
//   - Toxony mortar recipe (2026-10-17, cheaper) -> 'SPS' / ' S ': S = Supplementaries slidy block
//     ("sturdy mineral block"), P = Wayfarer's pestle (leather + 2 diorite, recipe re-added here).
//   - Wayfarer mortar recipe restored exactly as Wayfarer ships it: 'M M' / 'MMM' / 'S S'.
//   - The Wayfarer-mortar twin of every single-item Toxony grind is generated where that grind is defined (+25% chance of 1 extra).
//   - Toxony's own green-dye recipes are left as they are (on its own mortar already).

// ---- Wayfarer mortar grinding (2026-10-17, Derek) -------------------------------------------------
// Wayfarer's mortar (wayfarer_core:mortar) grinds ONE item at a time (recipe type wayfarer_core:grinding).
// Toxony's mortar takes up to 4 ingredients, but its recipes have a fixed output. Every single-item grind
// also exists for Wayfarer's mortar (it costs more to build): the SAME output as Toxony's, plus a 25%
// chance of ONE EXTRA item (bonus_chance / bonus_count), and a 60-tick grind. The recipe is generated by a
// small WF() helper inlined in the file that defines each Toxony grind (oowwo_small_ports.js, oowwo_wheat.js,
// oowwo_misc.js, oowwo_dyes.js, wayfarer_port.js) because KubeJS server scripts cannot assign to `global`.

ServerEvents.recipes(event => {
  const R = fn => { try { fn(); } catch (e) { console.warn('[mortars] skipped: ' + e); } };
  const RM = id => event.remove({ id: id });

  // Toxony mortar at Wayfarer's material tier. Derek 2026-10-17: cheaper - 3 sturdy mineral blocks + pestle.
  RM('toxony:mortar_pestle');
  R(() => event.shaped('toxony:mortar_pestle', ['SPS', ' S '], {
    S: 'supplementaries:slidy_block', P: 'wayfarer_core:pestle'
  }).id('oowwo:mortars/toxony_mortar'));
  // Wayfarer's own mortar, original recipe (from Wayfarer materials/mortar_and_pestle.js).
  R(() => event.shaped('wayfarer_core:mortar', ['M M', 'MMM', 'S S'], {
    M: 'supplementaries:slidy_block', S: 'minecraft:stick'
  }).id('oowwo:mortars/wayfarer_mortar'));
  // Wayfarer's pestle (its recipe from Wayfarer's mortar_and_pestle.js), the Toxony mortar ingredient.
  R(() => event.shaped('wayfarer_core:pestle', [' L ', ' D ', ' D '], {
    L: 'minecraft:leather', D: 'minecraft:diorite'
  }).id('oowwo:mortars/pestle'));
});
